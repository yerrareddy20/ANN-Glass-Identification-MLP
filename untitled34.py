import warnings
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, LabelEncoder
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix
)

warnings.filterwarnings("ignore", category=UserWarning)

RANDOM_STATE = 42

# ============================================================
# 1. LOAD THE DATASET
# ============================================================

url = (
    "https://archive.ics.uci.edu/ml/"
    "machine-learning-databases/glass/glass.data"
)

columns = [
    "ID", "RI", "Na", "Mg", "Al",
    "Si", "K", "Ca", "Ba", "Fe", "Type"
]

df = pd.read_csv(url, header=None, names=columns)

print("=" * 60)
print("ANN-BASED GLASS IDENTIFICATION USING MLP")
print("=" * 60)

print("\nFirst five rows:")
print(df.head())

print("\nDataset shape:", df.shape)

print("\nMissing values:")
print(df.isnull().sum())

# ============================================================
# 2. DATA PREPROCESSING
# ============================================================

# Remove ID because it is only an identifier
df.drop(columns=["ID"], inplace=True)

# Handle missing values, if any
df.dropna(inplace=True)

# Input features and target variable
X = df.drop(columns=["Type"])
y_original = df["Type"].astype(int)

# Encode target classes
encoder = LabelEncoder()
y = encoder.fit_transform(y_original)

class_labels = encoder.classes_

print("\nInput features:")
print(list(X.columns))

print("\nGlass classes:")
print(class_labels)

print("\nNumber of samples in each class:")
print(y_original.value_counts().sort_index())

# ============================================================
# 3. SPLIT THE DATASET
# ============================================================

# First, separate the final unseen test set
X_train_full, X_test, y_train_full, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=RANDOM_STATE,
    stratify=y
)

# Create training and validation sets
X_train, X_val, y_train, y_val = train_test_split(
    X_train_full,
    y_train_full,
    test_size=0.20,
    random_state=RANDOM_STATE,
    stratify=y_train_full
)

print("\nTraining samples:", len(X_train))
print("Validation samples:", len(X_val))
print("Testing samples:", len(X_test))

# ============================================================
# 4. FEATURE SCALING
# ============================================================

# Fit scaler only on training data to prevent data leakage
scaler = StandardScaler()

X_train_scaled = scaler.fit_transform(X_train)
X_val_scaled = scaler.transform(X_val)
X_test_scaled = scaler.transform(X_test)
X_train_full_scaled = scaler.transform(X_train_full)

# ============================================================
# 5. EVALUATION FUNCTION
# ============================================================

def evaluate_model(model, X_data, y_true):
    predictions = model.predict(X_data)

    return {
        "Accuracy": accuracy_score(y_true, predictions),
        "Precision": precision_score(
            y_true, predictions,
            average="macro", zero_division=0
        ),
        "Recall": recall_score(
            y_true, predictions,
            average="macro", zero_division=0
        ),
        "F1-score": f1_score(
            y_true, predictions,
            average="macro", zero_division=0
        )
    }

# ============================================================
# 6. BASELINE MODEL
# ============================================================

print("\n" + "=" * 60)
print("BASELINE MODEL TRAINING")
print("=" * 60)

baseline = MLPClassifier(
    hidden_layer_sizes=(16,),
    activation="relu",
    solver="sgd",
    learning_rate_init=0.01,
    batch_size=32,
    momentum=0.9,
    max_iter=1000,
    early_stopping=True,
    validation_fraction=0.15,
    n_iter_no_change=40,
    random_state=RANDOM_STATE
)

baseline.fit(X_train_scaled, y_train)

baseline_metrics = evaluate_model(
    baseline, X_val_scaled, y_val
)

print("\nBaseline validation results:")
for name, value in baseline_metrics.items():
    print(f"{name}: {value:.4f}")

print("Training iterations:", baseline.n_iter_)

# ============================================================
# 7. CONTROLLED EXPERIMENTS
# ============================================================

experiments = [
    {
        "name": "Baseline - 16 neurons",
        "layers": (16,),
        "lr": 0.01,
        "batch": 32,
        "alpha": 0.0001
    },
    {
        "name": "Proposed - 32,16 neurons",
        "layers": (32, 16),
        "lr": 0.01,
        "batch": 32,
        "alpha": 0.001
    },
    {
        "name": "Lower learning rate",
        "layers": (32, 16),
        "lr": 0.001,
        "batch": 32,
        "alpha": 0.001
    },
    {
        "name": "Smaller batch size",
        "layers": (32, 16),
        "lr": 0.01,
        "batch": 16,
        "alpha": 0.001
    }
]

results = []
models = {}

print("\n" + "=" * 60)
print("CONTROLLED EXPERIMENTS")
print("=" * 60)

for exp in experiments:

    model = MLPClassifier(
        hidden_layer_sizes=exp["layers"],
        activation="relu",
        solver="sgd",
        learning_rate_init=exp["lr"],
        batch_size=exp["batch"],
        momentum=0.9,
        alpha=exp["alpha"],
        max_iter=1200,
        early_stopping=True,
        validation_fraction=0.15,
        n_iter_no_change=50,
        random_state=RANDOM_STATE
    )

    model.fit(X_train_scaled, y_train)

    metrics = evaluate_model(
        model, X_val_scaled, y_val
    )

    results.append({
        "Experiment": exp["name"],
        "Hidden Layers": str(exp["layers"]),
        "Learning Rate": exp["lr"],
        "Batch Size": exp["batch"],
        "Accuracy": metrics["Accuracy"],
        "Precision": metrics["Precision"],
        "Recall": metrics["Recall"],
        "F1-score": metrics["F1-score"],
        "Epochs": model.n_iter_
    })

    models[exp["name"]] = (model, exp)

results_df = pd.DataFrame(results)

print("\nValidation comparison:")
print(results_df.round(4).to_string(index=False))

results_df.to_csv(
    "glass_ann_experiment_results.csv",
    index=False
)

# ============================================================
# 8. SELECT THE BEST CONFIGURATION
# ============================================================

# Select using validation macro F1-score
best_name = results_df.loc[
    results_df["F1-score"].idxmax(),
    "Experiment"
]

best_model, best_config = models[best_name]

print("\nSelected configuration:", best_name)

# ============================================================
# 9. TRAIN THE SELECTED MODEL
# ============================================================

print("\nTraining the selected model on all training data...")

final_model = MLPClassifier(
    hidden_layer_sizes=best_config["layers"],
    activation="relu",
    solver="sgd",
    learning_rate_init=best_config["lr"],
    batch_size=best_config["batch"],
    momentum=0.9,
    alpha=best_config["alpha"],
    max_iter=1200,
    early_stopping=True,
    validation_fraction=0.15,
    n_iter_no_change=50,
    random_state=RANDOM_STATE
)

final_model.fit(X_train_full_scaled, y_train_full)

# ============================================================
# 10. FINAL EVALUATION ON UNSEEN TEST DATA
# ============================================================

test_predictions = final_model.predict(X_test_scaled)

test_metrics = evaluate_model(
    final_model, X_test_scaled, y_test
)

print("\n" + "=" * 60)
print("FINAL TEST RESULTS")
print("=" * 60)

for name, value in test_metrics.items():
    print(f"{name}: {value:.4f}")

print("\nClassification Report:")

print(classification_report(
    y_test,
    test_predictions,
    labels=np.arange(len(class_labels)),
    target_names=[str(c) for c in class_labels],
    zero_division=0
))

pd.DataFrame([test_metrics]).to_csv(
    "glass_ann_final_test_metrics.csv",
    index=False
)

# ============================================================
# 11. CONFUSION MATRIX
# ============================================================

cm = confusion_matrix(
    y_test,
    test_predictions,
    labels=np.arange(len(class_labels))
)

plt.figure(figsize=(8, 6))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=class_labels,
    yticklabels=class_labels
)

plt.title("Confusion Matrix - Glass Identification")
plt.xlabel("Predicted Glass Type")
plt.ylabel("Actual Glass Type")
plt.tight_layout()

plt.savefig(
    "glass_ann_confusion_matrix.png",
    dpi=300
)

plt.show()

# ============================================================
# 12. TRAINING LOSS GRAPH
# ============================================================

plt.figure(figsize=(8, 5))

plt.plot(
    baseline.loss_curve_,
    label="Baseline Model"
)

plt.plot(
    final_model.loss_curve_,
    label="Selected Model"
)

plt.title("Training Loss Using SGD")
plt.xlabel("Training Iteration")
plt.ylabel("Loss")
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()

plt.savefig(
    "glass_ann_training_loss.png",
    dpi=300
)

plt.show()

# ============================================================
# 13. EXPERIMENT COMPARISON GRAPH
# ============================================================

plt.figure(figsize=(10, 5))

sns.barplot(
    data=results_df,
    x="Experiment",
    y="Accuracy"
)

plt.title("Baseline vs Proposed MLP Configuration")
plt.xlabel("Experiment")
plt.ylabel("Validation Accuracy")
plt.xticks(rotation=20, ha="right")
plt.tight_layout()

plt.savefig(
    "glass_ann_experiment_comparison.png",
    dpi=300
)

plt.show()

# ============================================================
# 14. PREDICTION FOR AN UNSEEN SAMPLE
# ============================================================

sample = X_test.iloc[[0]]

sample_scaled = scaler.transform(sample)

predicted_encoded = final_model.predict(sample_scaled)[0]

predicted_type = encoder.inverse_transform(
    [predicted_encoded]
)[0]

actual_type = encoder.inverse_transform(
    [y_test[0]]
)[0]

print("\n" + "=" * 60)
print("SAMPLE PREDICTION")
print("=" * 60)

print("\nSample chemical measurements:")
print(sample.to_string(index=False))

print("\nPredicted glass type:", predicted_type)
print("Actual glass type:", actual_type)

# ============================================================
# 15. SAVE THE TRAINED MODEL
# ============================================================

import joblib

joblib.dump(
    {
        "model": final_model,
        "scaler": scaler,
        "label_encoder": encoder,
        "features": list(X.columns)
    },
    "glass_ann_model.pkl"
)

print("\nSaved model: glass_ann_model.pkl")

print("\nGenerated files:")
print("1. glass_ann_experiment_results.csv")
print("2. glass_ann_final_test_metrics.csv")
print("3. glass_ann_confusion_matrix.png")
print("4. glass_ann_training_loss.png")
print("5. glass_ann_experiment_comparison.png")
print("6. glass_ann_model.pkl")

print("\nPROJECT EXECUTION COMPLETED!")

